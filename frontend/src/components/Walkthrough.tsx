import { CheckCircle2, Clock3, FileCode2, ShieldAlert, XCircle } from "lucide-react";
import type { ReviewResult } from "../lib/types";
import { estimatedEffort, qualityGate } from "./Charts";

function rating(score: number): { letter: string; cls: string } {
  if (score >= 90) return { letter: "A", cls: "rating-a" };
  if (score >= 75) return { letter: "B", cls: "rating-b" };
  if (score >= 60) return { letter: "C", cls: "rating-c" };
  if (score >= 40) return { letter: "D", cls: "rating-d" };
  return { letter: "E", cls: "rating-e" };
}

function fileRisk(review: ReviewResult, path: string): { label: string; cls: string } {
  const issues = review.issues.filter((i) => i.file === path);
  if (issues.some((i) => i.severity === "critical")) return { label: "High risk", cls: "risk-high" };
  if (issues.some((i) => i.severity === "high" || i.severity === "medium")) return { label: "Needs review", cls: "risk-mid" };
  if (issues.length) return { label: "Low risk", cls: "risk-low" };
  return { label: "Clean", cls: "risk-clean" };
}

export default function Walkthrough({ review }: { review: ReviewResult }) {
  const gate = qualityGate(review);
  const checks = [
    { name: "Security analysis", ok: (review.stats.critical ?? 0) === 0, detail: `${review.stats.critical ?? 0} critical · ${review.category_scores?.security ?? 100}/100` },
    { name: "Bug detection", ok: !review.issues.some((i) => i.category === "bug" && i.severity === "high"), detail: `${review.issues.filter((i) => i.category === "bug").length} findings` },
    { name: "Performance check", ok: !review.issues.some((i) => i.category === "performance" && (i.severity === "critical" || i.severity === "high")), detail: `${review.issues.filter((i) => i.category === "performance").length} findings` },
    { name: "Style & maintainability", ok: (review.category_scores?.style ?? 100) >= 60, detail: `${review.category_scores?.style ?? 100}/100` },
    { name: "Quality gate", ok: gate.passed, detail: gate.passed ? "All thresholds met" : gate.reasons[0] ?? "Threshold missed" },
  ];
  const effort = estimatedEffort(review);

  return (
    <div className="walkthrough">
      <div className="wt-main card">
        <div className="wt-head">
          <span className="wt-bot"><ShieldAlert size={16} /></span>
          <div>
            <div className="wt-title">Review walkthrough</div>
            <div className="wt-sub">Generated by PR Review Assistant · deterministic engine</div>
          </div>
          <span className={`wt-gate ${gate.passed ? "passed" : "failed"}`}>{gate.passed ? "Ready to merge" : "Changes requested"}</span>
        </div>
        <p className="wt-summary">{review.summary}</p>
        <div className="wt-meta">
          <span><Clock3 size={13} /> Est. fix effort <strong>{effort}</strong></span>
          <span><FileCode2 size={13} /> {review.stats.files_changed} file(s) · {review.stats.lines_added} line(s)</span>
          <span>Score <strong>{review.score}/100 ({review.grade})</strong></span>
        </div>

        <div className="wt-files-head">Files changed</div>
        <div className="wt-files">
          {review.files.map((f) => {
            const risk = fileRisk(review, f.path);
            return (
              <button key={f.path} className="wt-file" onClick={() => document.getElementById(`file-${f.path}`)?.scrollIntoView({ behavior: "smooth" })}>
                <FileCode2 size={14} />
                <span className="wt-file-path">{f.path}</span>
                <span className="wt-file-lang">{f.language}</span>
                <span className="wt-file-lines">+{f.lines_added}</span>
                <span className={`risk ${risk.cls}`}>{risk.label}</span>
                <span className="wt-file-issues">{f.issue_count} issue(s)</span>
              </button>
            );
          })}
        </div>

        <div className="wt-ratings">
          {Object.entries(review.category_scores ?? {}).map(([cat, score]) => {
            const r = rating(score);
            return (
              <div key={cat} className="wt-rating">
                <span className={`rating-badge ${r.cls}`}>{r.letter}</span>
                <div><div className="wt-rating-name">{cat}</div><div className="wt-rating-score">{score}/100</div></div>
              </div>
            );
          })}
        </div>
      </div>

      <div className="wt-checks card">
        <div className="wt-checks-head">Checks</div>
        {checks.map((c) => (
          <div key={c.name} className="wt-check">
            {c.ok ? <CheckCircle2 size={16} className="check-ok" /> : <XCircle size={16} className="check-fail" />}
            <div><div className="wt-check-name">{c.name}</div><div className="wt-check-detail">{c.detail}</div></div>
            <span className="wt-check-state">{c.ok ? "pass" : "fail"}</span>
          </div>
        ))}
      </div>
    </div>
  );
}
