"""Real LLM deep review using the *user's own* API key.

The key arrives per-request from the browser, is used for one call, and is
never stored server-side or logged. Findings are labelled as AI-generated
and kept separate from deterministic engine findings.
"""

import json

import httpx


async def deep_review(code: str, filename: str, api_key: str, provider: str) -> str:
    prompt = (
        "You are a senior code reviewer. Review this file for LOGIC bugs, "
        "edge cases and design problems that pattern-based tools miss. "
        "Be specific with line references. Format: short summary, then a "
        "bulleted list of findings with severity (high/medium/low). "
        "If the code is sound, say so plainly.\n\n"
        f"File: {filename}\n```\n{code[:20000]}\n```"
    )
    if provider == "gemini":
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}"
        payload = {"contents": [{"parts": [{"text": prompt}]}]}
        async with httpx.AsyncClient(timeout=60) as client:
            resp = await client.post(url, json=payload)
            resp.raise_for_status()
            data = resp.json()
        return data["candidates"][0]["content"]["parts"][0]["text"]

    async with httpx.AsyncClient(timeout=60) as client:
        resp = await client.post(
            "https://api.groq.com/openai/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}"},
            json={
                "model": "llama-3.3-70b-versatile",
                "temperature": 0.2,
                "messages": [{"role": "user", "content": prompt}],
            },
        )
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"]


def review_markdown(review: dict) -> str:
    """Markdown body posted to GitHub as the bot comment."""
    lines = [
        "## PR Review Assistant — automated review",
        "",
        f"**Score: {review['score']}/100 (Grade {review['grade']})**",
        "",
        review["summary"],
        "",
        "| Severity | Count |",
        "| --- | --- |",
    ]
    for sev in ("critical", "high", "medium", "low"):
        lines.append(f"| {sev} | {review['stats'].get(sev, 0)} |")
    if review.get("issues"):
        lines += ["", "### Top findings", ""]
        for issue in review["issues"][:10]:
            lines.append(
                f"- **[{issue['severity'].upper()}] {issue['title']}** "
                f"(`{issue['file']}:{issue['line']}`, {issue['rule_id']}) — {issue['suggestion']}"
            )
    lines += ["", "_Generated by PR Review Assistant (deterministic rules + AST). A human review is still recommended._"]
    return "\n".join(lines)


