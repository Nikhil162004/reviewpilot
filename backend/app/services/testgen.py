"""Starter unit-test generation from source structure.

Python: functions discovered via AST get pytest skeletons with happy-path,
edge-case and error placeholders. JavaScript/TypeScript: exported/plain
functions get Jest skeletons. The output is a starting point a developer
finishes — it is intentionally honest about that in its header comment.
"""

import ast
import re


def generate_python_tests(code: str, filename: str) -> str:
    module = filename.removesuffix(".py").replace("/", ".")
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return "# Could not parse the source file — fix syntax errors first.\n"
    functions = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")]
    if not functions:
        return "# No top-level functions found to generate tests for.\n"

    out = [
        '"""Starter tests generated by ReviewPilot.',
        "Fill in real inputs/outputs — generated cases mark intent, not truth.",
        '"""',
        "",
        "import pytest",
        "",
        f"from {module} import {', '.join(f.name for f in functions)}",
        "",
    ]
    for fn in functions:
        args = [a.arg for a in fn.args.args]
        call_args = ", ".join("None" for _ in args) or ""
        out += [
            f"class Test{fn.name.replace('_', ' ').title().replace(' ', '')}:",
            f"    def test_{fn.name}_happy_path(self):",
            f"        # TODO: replace Nones with representative inputs",
            f"        result = {fn.name}({call_args})",
            "        assert result is not None",
            "",
            f"    def test_{fn.name}_edge_cases(self):",
            "        # TODO: empty / boundary / maximal inputs",
            f"        result = {fn.name}({call_args})",
            "        assert result is not None",
            "",
        ]
        if args:
            out += [
                f"    def test_{fn.name}_rejects_bad_input(self):",
                "        with pytest.raises((TypeError, ValueError)):",
                f"            {fn.name}({', '.join(['object()'] * len(args))})",
                "",
            ]
    return "\n".join(out)


def generate_js_tests(code: str, filename: str) -> str:
    names = re.findall(r"(?:function\s+(\w+)|const\s+(\w+)\s*=\s*(?:\(|function))", code)
    functions = [a or b for a, b in names]
    if not functions:
        return "// No functions found to generate tests for.\n"
    module = "./" + re.sub(r"\.(ts|tsx|js|jsx)$", "", filename.split("/")[-1])
    joined = ", ".join(functions)
    out = [
        "/** Starter tests generated by ReviewPilot - fill in real cases. */",
        "const { " + joined + " } = require(\"" + module + "\");",
        "",
    ]
    for name in functions:
        out += [
            "describe(\"" + name + "\", () => {",
            "  it(\"handles the happy path\", () => {",
            "    expect(" + name + "()).toBeDefined();",
            "  });",
            "",
            "  it(\"handles edge cases\", () => {",
            "    expect(() => " + name + "(undefined)).not.toThrow();",
            "  });",
            "});",
            "",
        ]
    return "\n".join(out)


def generate_tests(code: str, filename: str) -> tuple[str, str]:
    """Return (test_code, test_filename)."""
    if filename.endswith(".py"):
        return generate_python_tests(code, filename), f"test_{filename.split('/')[-1]}"
    return generate_js_tests(code, filename), filename.split("/")[-1].replace(".ts", ".test.ts").replace(".js", ".test.js")
